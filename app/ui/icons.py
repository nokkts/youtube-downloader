def _svg(name: str, color: str) -> bytes:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{_PATHS[name]}</svg>').encode()


def pixmap(name: str, color: str = "#ECECEC", size: int = 18, dpr: float = 2.0) -> QPixmap:
    px = QPixmap(int(size * dpr), int(size * dpr))
    px.setDevicePixelRatio(dpr)
    px.fill(Qt.transparent)
    p = QPainter(px)
    QSvgRenderer(QByteArray(_svg(name, color))).render(p, QRectF(0, 0, size, size))
    p.end()
    return px


@lru_cache(maxsize=256)
def icon(name: str, color: str = "#ECECEC", disabled_color: str = "#5a5a5a", size: int = 18) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size), QIcon.Normal)
    ic.addPixmap(pixmap(name, disabled_color, size), QIcon.Disabled)
    return ic


def app_icon() -> QIcon:
    """Ícone do app: quadrado arredondado violeta com seta de download."""
    ic = QIcon()
    for size in (16, 24, 32, 48, 64, 128, 256):
        img = QImage(size, size, QImage.Format_ARGB32)
        img.fill(Qt.transparent)
        p = QPainter(img)
        p.setRenderHint(QPainter.Antialiasing)
        path = QPainterPath()
        path.addRoundedRect(QRectF(0, 0, size, size), size * 0.24, size * 0.24)
        p.fillPath(path, QColor("#7C6CFF"))
        inner = size * 0.58
        off = (size - inner) / 2
        QSvgRenderer(QByteArray(_svg("download", "#FFFFFF"))).render(p, QRectF(off, off, inner, inner))
        p.end()
        ic.addPixmap(QPixmap.fromImage(img))
    return ic
